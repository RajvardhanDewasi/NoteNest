const mongoose = require("mongoose");

const COLORS = [
  "#ffffff",
  "#fff3b0",
  "#ffd6d6",
  "#d6f5d6",
  "#d6e8ff",
  "#e9dcff",
  "#ffe2c6",
  "#d5f5ef",
  "#f6d9f0",
  "#e8edf2",
];

// "Other" is kept so notes you already saved with it stay valid
const CATEGORIES = ["Personal", "College", "Work", "Ideas", "Study", "Projects", "Other"];

// Notes in Trash are removed automatically after this many days.
// To disable auto-delete, remove the TTL index near the bottom of this file.
const TRASH_DAYS = 30;

const checklistItemSchema = new mongoose.Schema(
  {
    text: { type: String, required: true, trim: true, maxlength: 300 },
    completed: { type: Boolean, default: false },
  },
  { _id: false } // the client identifies items by position, not by id
);

const noteSchema = new mongoose.Schema(
  {
    title: { type: String, required: true, trim: true, maxlength: 100 },

    // Sanitized HTML from the rich text editor
    content: { type: String, trim: true, default: "", maxlength: 50000 },

    // Plain-text copy of content, generated by the server. Used for search.
    plainText: { type: String, default: "" },

    color: { type: String, enum: COLORS, default: "#ffffff" },
    category: { type: String, enum: CATEGORIES, default: "Personal" },

    tags: {
      type: [String],
      default: [],
      validate: {
        validator: (value) => value.length <= 12,
        message: "A note can have at most 12 tags",
      },
    },

    isPinned: { type: Boolean, default: false },
    isArchived: { type: Boolean, default: false },
    isDeleted: { type: Boolean, default: false },
    deletedAt: { type: Date, default: null },

    reminderAt: { type: Date, default: null },
    // true once the in-app alert has been shown for the current reminderAt
    reminderFired: { type: Boolean, default: false },

    viewedAt: { type: Date, default: null },

    noteType: { type: String, enum: ["standard", "checklist"], default: "standard" },

    checklistItems: {
      type: [checklistItemSchema],
      default: [],
      validate: {
        validator: (value) => value.length <= 200,
        message: "A checklist can have at most 200 items",
      },
    },
  },
  { timestamps: true }
);

// Speeds up the main dashboard query
noteSchema.index({ isDeleted: 1, isArchived: 1, isPinned: -1, updatedAt: -1 });

// Auto-delete notes TRASH_DAYS after they were moved to Trash.
// MongoDB ignores documents where deletedAt is null.
noteSchema.index({ deletedAt: 1 }, { expireAfterSeconds: 60 * 60 * 24 * TRASH_DAYS });

module.exports = mongoose.model("Note", noteSchema);